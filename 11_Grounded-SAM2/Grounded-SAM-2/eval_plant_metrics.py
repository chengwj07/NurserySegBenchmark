#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""Grounded-SAM-2 seedling validation set evaluation: GroundingDINO detection + SAM2 segmentation -> mmseg style accuracy table.

The same set of indicator caliber as 01~08 (mmseg) / 09_FM-SAM / 10_SAM3: whole set cumulative confusion matrix
(Reuse the SegConfusionMatrix of 09_FM-SAM/src/metrics.py), output
aAcc / mIoU / mAcc / mDice / mFscore / mPrecision / mRecall + category-by-category details,
Can be directly compared with the accuracy table of the mmseg series model.

Process (refer to 09_FM-SAM’s practice):
  1. GroundingDINO performs text detection on each picture of val (caption = 4 class names), and obtains the instance box + category
  2. SAM2 uses the [detection frame center point] as the point prompt (labels=1, no frame is passed) to segment the instance mask.
  3. The instance masks are merged into semantic category maps according to the detector confidence from high to low (high confidence occupies the overlapping area first)
  4. Cumulative confusion matrix with ann_dir ground truth mask (pixel 0=background, 1..4=species), output mmseg accuracy table
     (SegConfusionMatrix / format_metrics has the same origin as FM-SAM, aAcc/mIoU/... can be directly compared)

Usage (run under Grounded-SAM-2 directory, prerequisite: sam2 environment + weights in place):
  # For complete evaluation (inference + accuracy table), GroundingDINO gives priority to fine-tuned weights by default:
  python eval_plant_metrics.py
  # Recalculate the accuracy table only from existing prediction dump (skipping inference):
  python eval_plant_metrics.py --skip-infer --pred-json outputs/grounded_sam2_val_predictions.json
"""

import argparse
import json
import pathlib
import sys

import numpy as np
from tqdm import tqdm

SCRIPT_DIR = pathlib.Path(__file__).resolve().parent
REPO_ROOT = SCRIPT_DIR.parent.parent  # seg_exp/

# Make the grounding_dino / sam2 package importable (cwd is overwritten when running in the Grounded-SAM-2 directory, here’s the bottom line)
sys.path.insert(0, str(SCRIPT_DIR))
# Reuse the FM-SAM indicator code (pure numpy), ensuring the same caliber as 01~08
sys.path.insert(0, str(REPO_ROOT / "09_FM-SAM" / "src"))
from metrics import SegConfusionMatrix, format_metrics  # noqa: E402

DEFAULT_CLASS_NAMES = [
    "podocarpus macrophyllus",  # Podocarpus macrophyllus
    "sasanqua camellia",        # Camellia sasanqua
    "loropetalum chinense",     # Loropetalum chinense
    "ligustrum quihoui",        # Ligustrum quihoui
]

# Data path (relative to Grounded-SAM-2/)
VAL_IMG_DIR = REPO_ROOT / "data" / "img_dir" / "val"
VAL_ANN_DIR = REPO_ROOT / "data" / "ann_dir" / "val"
VAL_ANN_JSON = REPO_ROOT / "data" / "val_annotations.json"

SAM2_MODEL_CONFIG = "sam2/configs/sam2.1/sam2.1_hiera_l.yaml"
SAM2_CHECKPOINT = "checkpoints/sam2.1_hiera_large.pt"
GROUNDING_DINO_CONFIG = "grounding_dino/groundingdino/config/GroundingDINO_SwinT_OGC.py"
# The fine-tuned weights will be used first if they exist, otherwise they will fall back to the official pre-trained weights.
GROUNDING_DINO_CKPT_FINETUNED = SCRIPT_DIR.parent / "outputs" / "groundingdino_swint_ogc_finetuned.pth"
GROUNDING_DINO_CKPT_BASE = "gdino_checkpoints/groundingdino_swint_ogc.pth"


def decode_rle(rle: dict) -> np.ndarray:
    'Decode COCO RLE into HxW uint8 mask (compatible with counts as list/str).'
    from pycocotools import mask as mask_util
    if isinstance(rle.get("counts"), list):
        rle = mask_util.frPyObjects([rle], rle["size"][0], rle["size"][1])[0]
    return mask_util.decode(rle).astype(np.uint8)


def encode_rle(mask: np.ndarray) -> dict:
    'HxW bool/uint8 mask -> COCO RLE (counts are strings).'
    from pycocotools import mask as mask_util
    rle = mask_util.encode(np.asarray(mask[:, :, None], order="F", dtype=np.uint8))[0]
    rle["counts"] = rle["counts"].decode("utf-8")
    return rle


def load_gt_maps(ann_dir: pathlib.Path) -> dict:
    'Read all masks under ann_dir and return {file_name: HxW uint8 GT image} (0=background, 1..4=species).'
    import cv2
    gt_maps = {}
    for m in sorted(ann_dir.glob("*.png")):
        gt = cv2.imread(str(m), cv2.IMREAD_UNCHANGED)
        if gt is None:
            print(f"[警告] 读取 GT 失败: {m}, 跳过")
            continue
        gt = np.clip(gt, 0, 4)  # Out-of-bounds pixel values are processed as background
        gt_maps[m.name] = gt.astype(np.uint8)
    return gt_maps


def load_class_names() -> list:
    'Prioritize reading the class name from val_annotations.json generated by prepare_dataset.py to ensure consistency with training.'
    if VAL_ANN_JSON.exists():
        try:
            with open(VAL_ANN_JSON, encoding="utf-8") as f:
                names = json.load(f)["class_names"]
            if names:
                return names
        except Exception as e:  # noqa: BLE001
            print(f"[警告] 读取 {VAL_ANN_JSON} 失败 ({e}), 用默认类名")
    return DEFAULT_CLASS_NAMES


def build_phrase_to_cat(class_names: list) -> dict:
    'phrase (category text returned by predict) -> semantic category id (1..4). Returns None if not matched.'
    mapping = {}
    for idx, name in enumerate(class_names, start=1):
        key = name.strip().lower()
        mapping[key] = idx
        # Compatible with more/less spaces in the phrase
        mapping[key.replace(" ", "")] = idx
    return mapping


def run_inference(args, class_names):
    'Run GroundingDINO + SAM2 on the full graph of val, returning a COCO style prediction dict.'
    import cv2
    import torch
    from torchvision.ops import box_convert
    from sam2.build_sam import build_sam2
    from sam2.sam2_image_predictor import SAM2ImagePredictor
    from grounding_dino.groundingdino.util.inference import load_model, load_image, predict

    gdino_ckpt = args.gdino_ckpt
    if gdino_ckpt is None:
        gdino_ckpt = GROUNDING_DINO_CKPT_FINETUNED if GROUNDING_DINO_CKPT_FINETUNED.exists() \
            else GROUNDING_DINO_CKPT_BASE
    print(f"[加载] GroundingDINO: {GROUNDING_DINO_CONFIG} + {gdino_ckpt}")
    print(f"[加载] SAM2: {args.sam2_config} + {args.sam2_ckpt}")

    gdino_model = load_model(GROUNDING_DINO_CONFIG, gdino_ckpt, device=args.device)
    sam2_model = build_sam2(args.sam2_config, args.sam2_ckpt, device=args.device)
    sam2_predictor = SAM2ImagePredictor(sam2_model)

    caption = ". ".join(class_names) + "."
    print(f"[检测] caption: {caption}")
    print(f"[检测] box_threshold={args.box_threshold}, text_threshold={args.text_threshold}")

    phrase_to_cat = build_phrase_to_cat(class_names)
    img_files = sorted(VAL_IMG_DIR.glob("*.png"))
    print(f"[数据] val 图像 {len(img_files)} 张")

    images, annotations = [], []
    n_unmatched_phrase = 0
    n_failed = 0
    print(f"[推理] 开始处理 {len(img_files)} 张图 (每张约 1-2s, 全程约 10 分钟, 无输出属正常)")
    for img_id, img_path in enumerate(tqdm(img_files, desc="推理", total=len(img_files))):
        try:
            # load_image will resize the image to the short side 800: GDINO's normalized frame is based on the resized size
            image_source, image_tensor = load_image(str(img_path))
            h_orig, w_orig = image_source.shape[:2]
            h_resize, w_resize = image_tensor.shape[-2:]

            boxes_norm, confidences, phrases = predict(
                model=gdino_model, image=image_tensor, caption=caption,
                box_threshold=args.box_threshold, text_threshold=args.text_threshold,
                device=args.device,
            )

            if len(boxes_norm) == 0:
                images.append({"id": img_id, "file_name": img_path.name})
                continue

            # Normalized cxcywh (based on resize size) -> original image pixel xyxy:
            # The model outputs a normalized frame on the resized image, which needs to be enlarged according to the [original image] size to fall on the original image coordinates.
            boxes_xyxy = box_convert(
                boxes_norm * torch.tensor([w_orig, h_orig, w_orig, h_orig]),
                in_fmt="cxcywh", out_fmt="xyxy",
            ).numpy()

            # FM-SAM style: The center point of each detection frame is [individually] used as a SAM2 point prompt (labels=[1]).
            # Note that SAM2 treats multiple points in one call as multiple hints of the same object and will only return one mask.
            # So it must be called frame by frame; processed from high to low detection confidence, up to max_det=300 (consistent with FM-SAM).
            order = np.argsort(-confidences.numpy())[:300]
            sam2_predictor.set_image(image_source)
            masks_list, sam_scores = [], []
            for idx in order:
                bx = boxes_xyxy[idx]
                cx, cy = (bx[0] + bx[2]) / 2.0, (bx[1] + bx[3]) / 2.0
                with torch.autocast(device_type=args.device, dtype=torch.bfloat16):
                    m, sc, _ = sam2_predictor.predict(
                        point_coords=np.array([[cx, cy]], dtype=np.float32),
                        point_labels=np.array([1], dtype=np.int64),
                        box=None, multimask_output=False,
                    )
                masks_list.append(np.asarray(m[0] > 0, dtype=np.uint8))  # m: (1, H, W)
                sam_scores.append(float(sc[0]))
            masks = np.stack(masks_list)
            scores = np.asarray(sam_scores)
            confs_ord = confidences.numpy()[order]
            phrases_ord = [phrases[i] for i in order]
            boxes_ord = boxes_xyxy[order]

            images.append({"id": img_id, "file_name": img_path.name})
            for i, (mask, score, conf, phrase) in enumerate(
                    zip(masks, scores, confs_ord, phrases_ord)):
                cat = phrase_to_cat.get(phrase.strip().lower())
                if cat is None:
                    n_unmatched_phrase += 1
                    continue
                annotations.append({
                    "image_id": img_id,
                    "category_id": cat,
                    "bbox": [float(v) for v in boxes_ord[i]],
                    "score": float(score),
                    "conf": float(conf),
                    "segmentation": encode_rle(mask),
                })
        except Exception as e:  # noqa: BLE001
            n_failed += 1
            print(f"[警告] {img_path.name} 推理失败: {e}")

    if n_unmatched_phrase:
        print(f"[警告] {n_unmatched_phrase} 个实例的短语未匹配到任何类别, 已忽略")
    if n_failed:
        print(f"[警告] {n_failed} 张图推理失败")
    print(f"[预测] 实例数: {len(annotations)}")

    return {"class_names": class_names, "images": images, "annotations": annotations}


def build_pred_map(preds: list, h: int, w: int) -> np.ndarray:
    """Instance predictions for a certain image are combined into semantic category images (0=background, 1..4=species).

    FM-SAM caliber: Processed according to detector confidence from high to low, and high-confidence instances occupy the overlapping area first.
    """
    pred_map = np.zeros((h, w), dtype=np.uint8)
    import cv2
    for p in sorted(preds, key=lambda x: -x["conf"]):
        mask = decode_rle(p["segmentation"])
        if mask.shape[:2] != (h, w):
            mask = cv2.resize(mask, (w, h), interpolation=cv2.INTER_NEAREST)
        pred_map = np.where((pred_map == 0) & (mask > 0), p["category_id"], pred_map)
    return pred_map


def evaluate(args, class_names, predictions, gt_maps):
    'Accumulate confusion matrix and output mmseg style accuracy table (same caliber as FM-SAM).'
    num_classes = len(class_names) + 1  # With background
    # The Chinese display name consistent with the FM-SAM evaluation table (for display only, the category order corresponds to class_names)
    DISPLAY_NAMES = ["罗汉松", "茶梅", "红花继木", "亮晶女贞"]
    cm_names = ["background"] + DISPLAY_NAMES[:len(class_names)]
    cm = SegConfusionMatrix(num_classes, class_names=cm_names)

    pred_by_img = {}
    for p in predictions["annotations"]:
        pred_by_img.setdefault(int(p["image_id"]), []).append(p)

    id2fname = {img["id"]: img["file_name"] for img in predictions["images"]}
    n_imgs = 0
    for img_id, preds in sorted(pred_by_img.items()):
        fname = id2fname.get(img_id)
        if fname is None or fname not in gt_maps:
            continue
        gt = gt_maps[fname]
        pred_map = build_pred_map(preds, *gt.shape[:2])
        cm.update(pred_map, gt)
        n_imgs += 1

    # Pictures without detection frames are also included (all predictions are background, contributing TN)
    for fname, gt in gt_maps.items():
        if fname not in {id2fname.get(i) for i in pred_by_img}:
            cm.update(np.zeros_like(gt), gt)
            n_imgs += 1

    if n_imgs == 0:
        print("[评估] 没有任何图像参与评估, 请检查 --pred-json / 数据路径")
        sys.exit(1)

    metrics = cm.compute()
    text = format_metrics(metrics, title=f"Grounded-SAM-2 验证集评估结果 ({n_imgs} 张图像)")
    print(text)

    args.out_dir.mkdir(parents=True, exist_ok=True)
    with open(args.out_dir / "grounded_sam2_pixel_metrics.json", "w", encoding="utf-8") as f:
        json.dump(metrics, f, ensure_ascii=False, indent=2)
    (args.out_dir / "grounded_sam2_pixel_metrics.txt").write_text(text, encoding="utf-8")
    print(f"[评估] 精度表已保存: {args.out_dir / 'grounded_sam2_pixel_metrics.txt'}")
    return metrics


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--img-dir", type=pathlib.Path, default=VAL_IMG_DIR)
    parser.add_argument("--ann-dir", type=pathlib.Path, default=VAL_ANN_DIR)
    parser.add_argument("--class-names", default=None,
                        help="逗号分隔的 4 个英文类名; 默认从 data/val_annotations.json 读取")
    parser.add_argument("--gdino-ckpt", default=None,
                        help="GroundingDINO 权重; 默认优先 outputs/groundingdino_swint_ogc_finetuned.pth")
    parser.add_argument("--gdino-config", default=GROUNDING_DINO_CONFIG)
    parser.add_argument("--sam2-ckpt", default=SAM2_CHECKPOINT)
    parser.add_argument("--sam2-config", default=SAM2_MODEL_CONFIG)
    parser.add_argument("--box-threshold", type=float, default=0.35)
    parser.add_argument("--text-threshold", type=float, default=0.25)
    parser.add_argument("--device", default="cuda")
    parser.add_argument("--pred-json", type=pathlib.Path,
                        default=pathlib.Path("outputs/grounded_sam2_val_predictions.json"))
    parser.add_argument("--out-dir", type=pathlib.Path,
                        default=pathlib.Path("outputs/grounded_sam2_eval"))
    parser.add_argument("--skip-infer", action="store_true",
                        help="不跑推理, 直接用 --pred-json 里已有的预测算指标")
    args = parser.parse_args()

    class_names = (args.class_names.split(",") if args.class_names
                   else load_class_names())
    assert len(class_names) == len(set(class_names)) and len(class_names) >= 1, \
        "class_names 需为非重复的类别名列表"

    gt_maps = load_gt_maps(args.ann_dir)
    print(f"[数据] GT 图像 {len(gt_maps)} 张")

    if args.skip_infer:
        if not args.pred_json.exists():
            print(f"[错误] --pred-json 不存在: {args.pred_json}")
            sys.exit(1)
        with open(args.pred_json, encoding="utf-8") as f:
            predictions = json.load(f)
    else:
        predictions = run_inference(args, class_names)
        args.pred_json.parent.mkdir(parents=True, exist_ok=True)
        with open(args.pred_json, "w", encoding="utf-8") as f:
            json.dump(predictions, f, ensure_ascii=False, indent=2)
        print(f"[预测] 已 dump: {args.pred_json}")

    evaluate(args, class_names, predictions, gt_maps)


if __name__ == "__main__":
    main()
