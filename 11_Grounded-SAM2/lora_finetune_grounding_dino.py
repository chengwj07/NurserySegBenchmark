"""
LoRA fine-tuning Grounding DINO (original open source repository, detector actually called by Grounded-SAM-2)
Warehouse: https://github.com/IDEA-Research/GroundingDINO

Adaptation instructions (relative to the initial version):
  - Data format alignment for your new dataset: generated by prepare_dataset.py train_annotations.json /
    val_annotations.json, structure {class_names, images[{image_path, boxes_xyxy, class_ids}]}
  - The training link is transformed into actual operation: NestedTensor input + official same positive_map
    (build_captions_and_token_span + create_positive_map_from_span) +
    Self-contained criterion (grounding_dino_criterion.py, Hungarian matching + focal + L1/GIoU)
  - Spell out all the breed names in the caption, and mark only the span of the breed in the current picture as a positive sample, so that the model can learn to "distinguish similar breeds"
  - Save: Each checkpoint is saved in the LoRA adapter; after training, it is automatically merged and can be directly
    Grounded-SAM-2 load_model loaded with complete weights ({"model": state_dict})

Prerequisites (environmental issues are temporarily put on hold, required before resuming training):
  1. GroundingDINO has been installed according to the official README (requires CUDA to compile the Deformable Attention operator)
  2. Pre-training weights groundingdino_swint_ogc.pth
  3. pip install peft

Usage:
  python lora_finetune_grounding_dino.py       --data_root ../data --config GroundingDINO/groundingdino/config/GroundingDINO_SwinT_OGC.py       --ckpt groundingdino_swint_ogc.pth --epochs 20 --batch_size 4 --out_dir outputs
"""

import argparse
import json
import os
import random
import sys

import torch
import torch.nn as nn
from torch.utils.data import DataLoader, Dataset

from PIL import Image
import torchvision.transforms as T
from transformers import AutoTokenizer

# Allow the script to import the local groundingdino package (when the warehouse is not pip installed)
_SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(_SCRIPT_DIR, "GroundingDINO"))

from groundingdino.models import build_model
from groundingdino.util.slconfig import SLConfig
from groundingdino.util.utils import clean_state_dict
from groundingdino.util.misc import nested_tensor_from_tensor_list
from groundingdino.util.vl_utils import (
    build_captions_and_token_span,
    create_positive_map_from_span,
)

from grounding_dino_criterion import HungarianMatcher, GroundingDINOCriterion

MAX_TEXT_LEN = 256


# ------------------------------------------------------------------
# 1. Load the official pre-trained model
# ------------------------------------------------------------------
def load_base_model(config_path, ckpt_path, device="cuda"):
    args = SLConfig.fromfile(config_path)
    args.device = device
    model = build_model(args)
    checkpoint = torch.load(ckpt_path, map_location="cpu")
    state = clean_state_dict(checkpoint["model"])
    missing, unexpected = model.load_state_dict(state, strict=False)
    if len(missing) or len(unexpected):
        print(f"[载入] missing {len(missing)} 个, unexpected {len(unexpected)} 个 key")
        if len(missing):
            print("  missing 示例:", missing[:5])
        if len(unexpected):
            print("  unexpected 示例:", unexpected[:5])
    return model.to(device)


# ------------------------------------------------------------------
# 2. Freeze all parameters and only inject LoRA into the Linear layer related to "text-visual alignment"
# Target modules: decoder’s cross-attention, encoder’s text/fusion layers, BERT’s q/k/v/dense
# bbox_embed (MLP) has a very small number of parameters and remains fully trainable.
# ------------------------------------------------------------------
LORA_TARGET_KEYWORDS = [
    "cross_attn",      # Image and text cross attention in decoder
    "text_layers",     # text self-attn / text-enhancer in encoder
    "fusion_layers",   # Image and text feature fusion layer (bi-attn)
    "bert",            # text backbone (BERT) internal q/k/v/dense
]


def build_lora_target_modules(model: nn.Module):
    targets = []
    for name, module in model.named_modules():
        if isinstance(module, nn.Linear) and any(k in name for k in LORA_TARGET_KEYWORDS):
            targets.append(name)
    return targets


def attach_lora(model: nn.Module, r=8, alpha=16, dropout=0.05):
    from peft import LoraConfig, inject_adapter_in_model

    for p in model.parameters():
        p.requires_grad = False

    target_modules = build_lora_target_modules(model)
    print(f"[LoRA] 命中 {len(target_modules)} 个 Linear 层, 示例: {target_modules[:5]}")

    lora_cfg = LoraConfig(
        r=r,
        lora_alpha=alpha,
        lora_dropout=dropout,
        target_modules=target_modules,
        bias="none",
    )
    model = inject_adapter_in_model(lora_cfg, model)

    # bbox_embed / class_embed output header parameters are very small, keeping the full amount trainable
    # (class_embed is ContrastiveEmbed, no parameters, this is just insurance)
    for name, p in model.named_parameters():
        if "bbox_embed" in name or "class_embed" in name:
            p.requires_grad = True

    trainable = sum(p.numel() for p in model.parameters() if p.requires_grad)
    total = sum(p.numel() for p in model.parameters())
    print(f"[LoRA] 可训练参数: {trainable / 1e6:.2f}M / 总参数: {total / 1e6:.2f}M "
          f"({100 * trainable / total:.2f}%)")
    return model


# ------------------------------------------------------------------
# 3. Dataset: Read train_annotations.json / val_annotations.json generated by prepare_dataset.py
# ------------------------------------------------------------------
class FineGrainedSpeciesDataset(Dataset):
    def __init__(self, ann_json, tokenizer_name="bert-base-uncased", is_train=True):
        with open(ann_json, "r", encoding="utf-8") as f:
            data = json.load(f)
        self.class_names = data["class_names"]       # English prompt in the same order as data.yaml
        self.records = data["images"]
        self.tokenizer = AutoTokenizer.from_pretrained(tokenizer_name)
        self.is_train = is_train
        self.transform = T.Compose([
            T.ToTensor(),
            T.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225]),
        ])

    def __len__(self):
        return len(self.records)

    def _build_caption_and_spans(self):
        'Scramble all the variety names to spell caption, and return caption + {class name: [[char_beg, char_end], ...]}'
        names = self.class_names[:]
        random.shuffle(names)  # Avoid model remembering "first class = correct answer"
        caption, cat2tokenspan = build_captions_and_token_span(names, force_lowercase=True)
        return caption, cat2tokenspan

    def __getitem__(self, idx):
        rec = self.records[idx]
        image = Image.open(rec["image_path"]).convert("RGB")
        w, h = image.size  # Use real size for normalization without hard-coding 1024
        image = self.transform(image)

        caption, cat2tokenspan = self._build_caption_and_spans()

        boxes_xyxy = torch.tensor(rec["boxes_xyxy"], dtype=torch.float32)  # [n,4] pixels
        class_ids = rec["class_ids"]

        # Pixel coordinates -> normalized cxcywh (GroundingDINO internal box format)
        cx = (boxes_xyxy[:, 0] + boxes_xyxy[:, 2]) / 2 / w
        cy = (boxes_xyxy[:, 1] + boxes_xyxy[:, 3]) / 2 / h
        bw = (boxes_xyxy[:, 2] - boxes_xyxy[:, 0]) / w
        bh = (boxes_xyxy[:, 3] - boxes_xyxy[:, 1]) / h
        boxes_cxcywh = torch.stack([cx, cy, bw, bh], dim=1)

        # The category of each box -> the character span of the category name in the caption -> token span -> positive_map
        tokenized = self.tokenizer(caption, return_offsets_mapping=True, add_special_tokens=True)
        token_spans = [cat2tokenspan[self.class_names[cid]] for cid in class_ids]
        positive_map = create_positive_map_from_span(tokenized, token_spans, MAX_TEXT_LEN)

        target = {
            "boxes": boxes_cxcywh,
            "labels": torch.tensor(class_ids, dtype=torch.long),
            "positive_map": positive_map,          # [n, 256], row normalization
            "caption": caption,
        }
        return image, target


def collate_fn(batch):
    images = [b[0] for b in batch]
    targets = [b[1] for b in batch]
    samples = nested_tensor_from_tensor_list(images)
    return samples, targets


# ------------------------------------------------------------------
# 4. LoRA weight merging (complete weights exported to Grounded-SAM-2)
# ------------------------------------------------------------------
def merge_lora_weights(model):
    'Write LoRA delta back to base weights (peft universal manual merge of lora.Linear)'
    with torch.no_grad():
        for name, module in model.named_modules():
            lora_A = getattr(module, "lora_A", None)
            lora_B = getattr(module, "lora_B", None)
            if lora_A is None or lora_B is None:
                continue
            wa = lora_A.default.weight
            wb = lora_B.default.weight
            scaling = getattr(module, "scaling", 1.0)
            if isinstance(scaling, dict):
                scaling = scaling.get("default", 1.0)
            delta = (wb @ wa) * float(scaling)
            if getattr(module, "fan_in_fan_out", False):
                module.weight.data += delta.t()
            else:
                module.weight.data += delta
    return model


def export_merged_ckpt(config_path, base_ckpt_path, lora_adapter_path, out_path, device,
                       lora_r=8, lora_alpha=16, lora_dropout=0.05):
    """Load the LoRA adapter with a new model -> Merge -> Save to Grounded-SAM-2 directly loadable format

    Pay attention to two points, otherwise the exported weights will miss the entire text encoder when loaded downstream:
      1. The adapter key exported by get_peft_model_state_dict is flat lora_A.weight,
         After injection, the model contains lora_A.default.weight, which needs to be restored before loading;
      2. After merging, the LoRA packaging layer in state_dict has the base_layer prefix, which needs to be stripped off when exporting.
         And discard the lora_A/lora_B parameters and restore to the ordinary Linear key structure.
    """
    model = load_base_model(config_path, base_ckpt_path, device=device)
    model = attach_lora(model, r=lora_r, alpha=lora_alpha, dropout=lora_dropout)
    lora_state = torch.load(lora_adapter_path, map_location="cpu")
    lora_state = {k.replace(".lora_A.weight", ".lora_A.default.weight")
                    .replace(".lora_B.weight", ".lora_B.default.weight"): v
                  for k, v in lora_state.items()}
    model.load_state_dict(lora_state, strict=False)
    merge_lora_weights(model)

    sd = {}
    for k, v in model.state_dict().items():
        if ".lora_A." in k or ".lora_B." in k:
            continue
        sd[k.replace(".base_layer.", ".")] = v
    # Self-check: Ordinary models must be able to be loaded with zero missing, otherwise downstream inference will be initialized randomly.
    args = SLConfig.fromfile(config_path)
    args.device = device
    check = build_model(args)
    res = check.load_state_dict(clean_state_dict(sd), strict=False)
    assert not res.missing_keys, f"合并导出不完整, missing {res.missing_keys[:5]}"
    torch.save({"model": clean_state_dict(sd)}, out_path)
    print(f"[导出] 合并权重已保存: {out_path}")


# ------------------------------------------------------------------
# 5. Training loop
# ------------------------------------------------------------------
def train(args):
    device = args.device
    model = load_base_model(args.config, args.ckpt, device=device)
    model = attach_lora(model, r=args.lora_r, alpha=args.lora_alpha, dropout=args.lora_dropout)

    train_json = os.path.join(args.data_root, "train_annotations.json")
    val_json = os.path.join(args.data_root, "val_annotations.json")
    dataset = FineGrainedSpeciesDataset(train_json, is_train=True)
    loader = DataLoader(dataset, batch_size=args.batch_size, shuffle=True,
                        num_workers=args.num_workers, collate_fn=collate_fn,
                        drop_last=True)

    matcher = HungarianMatcher()
    criterion = GroundingDINOCriterion(matcher).to(device)

    trainable_params = [p for p in model.parameters() if p.requires_grad]
    optimizer = torch.optim.AdamW(trainable_params, lr=args.lr, weight_decay=args.weight_decay)
    scaler = torch.cuda.amp.GradScaler(enabled=args.amp)

    os.makedirs(args.out_dir, exist_ok=True)
    print(f"[数据] train {len(dataset)} 张, 类别: {dataset.class_names}")
    print(f"[数据] batch_size={args.batch_size}, 每步匹配 GT 框约 "
          f"{sum(len(r['boxes_xyxy']) for r in dataset.records) // len(dataset)} 个")

    model.train()
    for epoch in range(args.epochs):
        epoch_losses = {}
        num_steps = 0
        for samples, targets in loader:
            samples = samples.to(device)
            targets = [{k: (v.to(device) if torch.is_tensor(v) else v)
                        for k, v in t.items()} for t in targets]

            with torch.cuda.amp.autocast(enabled=args.amp):
                outputs = model(samples, targets=targets)
                loss_dict = criterion(outputs, targets)
                losses = loss_dict["loss_total"]

            optimizer.zero_grad()
            scaler.scale(losses).backward()
            scaler.step(optimizer)
            scaler.update()

            for k, v in loss_dict.items():
                epoch_losses[k] = epoch_losses.get(k, 0.0) + float(v.detach())
            num_steps += 1

        avg = {k: v / num_steps for k, v in epoch_losses.items()}
        print(f"epoch {epoch + 1}/{args.epochs} | "
              + " | ".join(f"{k}={v:.4f}" for k, v in sorted(avg.items())), flush=True)

        # End export of each epoch (only small adapters are saved; complete weights will eventually be merged)
        adapter_path = os.path.join(args.out_dir, f"lora_species_epoch{epoch + 1}.pt")
        from peft import get_peft_model_state_dict
        torch.save(get_peft_model_state_dict(model), adapter_path)

    # End of training: merge the last LoRA adapter into complete weights for direct loading by Grounded-SAM-2
    final_adapter = os.path.join(args.out_dir, f"lora_species_epoch{args.epochs}.pt")
    final_ckpt = os.path.join(args.out_dir, "groundingdino_swint_ogc_finetuned.pth")
    export_merged_ckpt(args.config, args.ckpt, final_adapter, final_ckpt, device,
                       args.lora_r, args.lora_alpha, args.lora_dropout)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--data_root", default="../data")
    parser.add_argument("--config",
                        default=os.path.join(_SCRIPT_DIR, "GroundingDINO/groundingdino/config/GroundingDINO_SwinT_OGC.py"))
    parser.add_argument("--ckpt", default="groundingdino_swint_ogc.pth")
    parser.add_argument("--out_dir", default=os.path.join(_SCRIPT_DIR, "outputs"))
    parser.add_argument("--epochs", type=int, default=20)
    parser.add_argument("--batch_size", type=int, default=4)
    parser.add_argument("--lr", type=float, default=1e-4)
    parser.add_argument("--weight_decay", type=float, default=1e-4)
    parser.add_argument("--lora_r", type=int, default=8)
    parser.add_argument("--lora_alpha", type=int, default=16)
    parser.add_argument("--lora_dropout", type=float, default=0.05)
    parser.add_argument("--num_workers", type=int, default=4)
    parser.add_argument("--device", default="cuda")
    parser.add_argument("--amp", action="store_true",
                        help="开启混合精度 (GroundingDINO 的 deformable attention 自定义算子对 AMP 兼容性一般, 默认关)")
    args = parser.parse_args()
    train(args)


if __name__ == "__main__":
    main()
