"""
06_oneformer/eval.py

Use a trained checkpoint (such as output_dir/best) to recalculate the indicator on the verification set. No need
Retrain. The index conventions is exactly the same as what was printed during the train.py training process, and also the same as that of the other 7 mmseg models.
`IoUMetric(iou_metrics=[\"mIoU\",\"mDice\",\"mFscore\"])` The output conventions is the same (aAcc/mIoU/mAcc/mDice/
mFscore/mPrecision/mRecall), can be directly compared together.

Usage:
    python eval.py         --checkpoint ./work_dirs/oneformer/best         --data_root /path/to/work_data_root         [--batch_size 1] [--out_file ./work_dirs/oneformer/eval_best.json]

--checkpoint is the directory where train.py is saved using save_checkpoint() (it contains model.safetensors +
config.json + processor configuration), it is no longer a separate .pth weight file, and there is no need to specify additional --pretrained
——The model structure and processor configuration have been completely saved in this directory.
"""
import argparse
import json
import os
import sys

import torch
from torch.utils.data import DataLoader

sys.path.insert(0, os.path.dirname(__file__))
from dataset import SegFolderDataset
from engine import CLASSES, NUM_CLASSES, collate_fn, evaluate, format_metrics, load_model_and_processor


def parse_args():
    parser = argparse.ArgumentParser()
    parser.add_argument("--checkpoint", type=str, required=True,
                         help='The checkpoint directory saved by train.py, such as ./work_dirs/oneformer/best')
    parser.add_argument("--data_root", type=str, required=True,
                         help='work_data_root generated by prepare_data.py (will be divided by val)')
    parser.add_argument("--split", type=str, default="val", choices=["val", "train"],
                         help='Which division is used to calculate the index? The default is val; if you want to check whether it is overfitting, you can pass train')
    parser.add_argument("--batch_size", type=int, default=1)
    parser.add_argument("--image_size", type=int, default=512)
    parser.add_argument("--out_file", type=str, default=None,
                         help='Optional, save the complete indicator (including the respective values for each category) as a json file')
    parser.add_argument("--device", type=str, default="cuda" if torch.cuda.is_available() else "cpu")
    return parser.parse_args()


def main():
    args = parse_args()

    model, processor = load_model_and_processor(pretrained=None, device=args.device,
                                                  checkpoint=args.checkpoint)

    eval_set = SegFolderDataset(args.data_root, args.split, processor, args.image_size,
                                 num_classes=NUM_CLASSES)
    eval_loader = DataLoader(eval_set, batch_size=args.batch_size, shuffle=False,
                              num_workers=2, collate_fn=collate_fn)

    metrics = evaluate(model, processor, eval_loader, args.device)

    print(f"checkpoint: {args.checkpoint}")
    print(f"split: {args.split}  ({len(eval_set)} Zhang)")
    print(f"val_loss={metrics['loss']:.4f}")
    print(format_metrics(metrics))
    print()
    print('Complete Indicators (Category: ' + ", ".join(f"{i}={name}" for i, name in enumerate(CLASSES)) + "):")
    for k, v in metrics.items():
        print(f"  {k}: {v:.4f}" if isinstance(v, float) else f"  {k}: {v}")

    if args.out_file:
        os.makedirs(os.path.dirname(os.path.abspath(args.out_file)), exist_ok=True)
        with open(args.out_file, "w") as f:
            json.dump(
                {"checkpoint": args.checkpoint, "split": args.split, "num_samples": len(eval_set),
                 **metrics},
                f, indent=2, ensure_ascii=False,
            )
        print(f"\\nThe complete indicator has been saved to {args.out_file}")


if __name__ == "__main__":
    main()
