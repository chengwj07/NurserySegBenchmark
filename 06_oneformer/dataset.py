"""
06_oneformer/dataset.py

OneFormer is not within the official support range of mmsegmentation, so this model uses
OneFormerForUniversalSegmentation implementation of the HuggingFace `transformers` library
(Semantic segmentation task mode task_inputs=\"semantic\").

This file defines a Dataset that reads the img_dir/ann_dir structure generated by common/prepare_data.py.
Supports two categories and multiple categories: the mask pixel value is the category index (0=background, 1..N-1=other categories),
It is consistent with the convention used by the mmseg model in common/plant_dataset.py / common/binary_dataset.py.
"""
from pathlib import Path

import numpy as np
import torch
from PIL import Image
from torch.utils.data import Dataset


class SegFolderDataset(Dataset):
    """Read png image/mask pairs under img_dir/{split} and ann_dir/{split}.

    Args:
        num_classes: Total number of segmentation classes (including background). Default 2 = binary segmentation. Multiple categories such as
            Background=0/Podocarpus macrophyllus=1/Camellia sasanqua=2/Loropetalum chinense=3/Ligustrum quihoui=4 Pass 5, need to follow
            common/prepare_data.py uses --num_classes to be consistent when converting data.
    """

    def __init__(self, data_root: str, split: str, processor, image_size: int = 512,
                 num_classes: int = 2):
        self.img_dir = Path(data_root) / "img_dir" / split
        self.ann_dir = Path(data_root) / "ann_dir" / split
        self.processor = processor
        self.image_size = image_size
        self.num_classes = num_classes

        self.img_files = sorted(self.img_dir.glob("*.png"))
        assert len(self.img_files) > 0, f"Not here {self.img_dir} find any png image"

    def __len__(self):
        return len(self.img_files)

    def __getitem__(self, idx):
        img_path = self.img_files[idx]
        ann_path = self.ann_dir / img_path.name

        image = Image.open(img_path).convert("RGB")
        mask = np.array(Image.open(ann_path).convert("L")).astype(np.int64)
        # The mask pixel value itself is the class index (guaranteed by common/prepare_data.py to be in the range [0, num_classes-1]),
        # No binarization is done. Only one defensive pruning is done here to avoid individual dirty data causing OneFormer internal data by category.
        # When building one-hot/embedding, an out-of-bounds error is reported.
        mask = np.clip(mask, 0, self.num_classes - 1)

        # OneFormer processor requires task_inputs text prompt ("semantic")
        # and (image, semantic map) are encoded together as model input (mask classification paradigm:
        # It will be converted internally into a set of mask_labels/class_labels instead of a dense pixel-by-pixel label map)
        inputs = self.processor(
            images=image,
            segmentation_maps=mask,
            task_inputs=["semantic"],
            return_tensors="pt",
        )
        # The processor will add one dimension to the batch dimension, and here we take out a single sample
        item = {k: v.squeeze(0) if hasattr(v, "squeeze") else v[0] for k, v in inputs.items()}

        # Additional retention of dense class index masks and original dimensions at original resolution for verification phase calculations
        # Accuracy/Recall/F1/IoU/Dice - these two fields are not passed to model.forward(),
        # In the training/validation loop, they are taken out of the batch and processed separately before calling the model.
        item["raw_mask"] = torch.from_numpy(mask)
        item["orig_size"] = (mask.shape[0], mask.shape[1])
        return item
