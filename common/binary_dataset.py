"""
common/binary_dataset.py

Register a binary (background/foreground) dataset in the mmsegmentation dataset registry,
For U-Net / DeepLabV3+ / HRNet / SegFormer / Swin-UperNet / InternImage / VMamba
shared. All model config files pass:

    custom_imports = dict(imports=['common.binary_dataset'], allow_failed_imports=False)

to load this module to use `BinarySegDataset`.

Dataset directory structure (generated by common/prepare_data.py):
    img_dir/train, img_dir/val -> original image .png
    ann_dir/train, ann_dir/val -> mask .png (pixel value 0/1)
"""
from mmseg.datasets import BaseSegDataset
from mmseg.registry import DATASETS


@DATASETS.register_module()
class BinarySegDataset(BaseSegDataset):
    'Two-class segmentation dataset: 0=background, 1=foreground.'

    METAINFO = dict(
        classes=("background", "foreground"),
        palette=[[0, 0, 0], [255, 255, 255]],
    )

    def __init__(self, **kwargs):
        super().__init__(
            img_suffix=".png",
            seg_map_suffix=".png",
            reduce_zero_label=False,
            **kwargs,
        )
