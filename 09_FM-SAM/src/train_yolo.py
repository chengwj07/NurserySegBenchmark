"""YOLO26 detection fine-tuning training module.

The YOLO26 detection model is fine-tuned on the user dataset for subsequent positioning of foreground targets.
Unused GPU memory cached by PyTorch is automatically released after each round of training to prevent continuous growth of the memory.
"""
import gc
import pathlib


def _release_gpu_cache(trainer):
    """Ultralytics callback: Release GPU cache after each round of training + validation.

    PyTorch's CUDA allocator caches allocated GPU memory blocks for reuse, but does not actively release them back to the system.
    This callback calls gc.collect() + torch.cuda.empty_cache() after each round,
    Return unused cached GPU memory to the GPU.
    """
    gc.collect()
    try:
        import torch
        if torch.cuda.is_available():
            torch.cuda.empty_cache()
    except ImportError:
        pass


def train_yolo(
    data_yaml: str,
    model: str = "yolo26n.pt",
    epochs: int = 100,
    imgsz: int = 640,
    batch: int = 16,
    device: str = "cpu",
    project: str = "runs",
    name: str = "yolo26_train",
    patience: int = 20,
    resume: bool = False,
) -> str:
    """Fine-tuning the YOLO26 detection model.

    Args:
        data_yaml: data.yaml file path (generated by data_prep).
        model: YOLO model name or weight path.
               - \"yolo26n.pt\": Load pretrained weights fine-tuning (requires Internet connection to download)
               - \"yolo26n.yaml\": build from scratch (no need to download, for testing)
        epochs: The number of training rounds (it is also the total number of rounds when training is resumed from a breakpoint, continuing from the completed rounds).
        imgsz: training image size.
        batch: batch size.
        device: training equipment.
        project: The result is saved in the project directory.
        name: Experiment name.
        patience: early stop patience value.
        resume: Whether to resume training from a breakpoint. is True from
            {project}/{name}/weights/last.pt is loaded (including weights/optimizers/number of rounds),
            Continue training for total epochs.

    Returns:
        Best weight file path (best.pt).
    """
    from ultralytics import YOLO

    if resume:
        # Ultralytics official training resumption process: train(resume=True) after loading last.pt
        ckpt = str(pathlib.Path(project) / name / "weights" / "last.pt")
        if not pathlib.Path(ckpt).exists():
            raise FileNotFoundError(
                f"[YOLO] Breakpoint file does not exist: {ckpt}(It needs to be trained normally for at least 1 round to generate last.pt)"
            )
        print(f"[YOLO] Continue training at breakpoint, load: {ckpt}")
        yolo = YOLO(ckpt)
        train_kwargs = {"resume": True}
    else:
        print(f"[YOLO] Load model: {model}")
        yolo = YOLO(model)
        train_kwargs = {}

    # Register callback: release GPU cache memory after each round
    yolo.add_callback("on_fit_epoch_end", _release_gpu_cache)

    print(f"[YOLO] Start training: epochs={epochs}, imgsz={imgsz}, batch={batch}, device={device}"
          + (", resume=True" if resume else ""))
    results = yolo.train(
        data=data_yaml,
        epochs=epochs,
        imgsz=imgsz,
        batch=batch,
        device=device,
        project=project,
        name=name,
        patience=patience,
        exist_ok=True,
        cache=False,
        **train_kwargs,
    )

    # Get the optimal weight path
    save_dir = pathlib.Path(results.save_dir) if hasattr(results, "save_dir") else None
    if save_dir is None:
        save_dir = pathlib.Path(project) / name
    best_pt = save_dir / "weights" / "best.pt"
    if not best_pt.exists():
        last_pt = save_dir / "weights" / "last.pt"
        if last_pt.exists():
            best_pt = last_pt
        else:
            raise FileNotFoundError(f"The weight file was not found after training was completed: {best_pt}")

    # Release once at the end of training
    _release_gpu_cache(None)

    print(f"[YOLO] training completed, optimal weight: {best_pt}")
    return str(best_pt)


if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser(description='Fine-tuning the YOLO26 detection model')
    parser.add_argument("--data", required=True, help='data.yaml path')
    parser.add_argument("--model", default="yolo26n.pt", help='Model name or weight path')
    parser.add_argument("--epochs", type=int, default=100)
    parser.add_argument("--imgsz", type=int, default=640)
    parser.add_argument("--batch", type=int, default=16)
    parser.add_argument("--device", default="cpu")
    parser.add_argument("--resume", action="store_true",
                        help='Resume training from project/name/weights/last.pt breakpoint')
    args = parser.parse_args()
    train_yolo(args.data, args.model, args.epochs, args.imgsz, args.batch,
               args.device, resume=args.resume)
