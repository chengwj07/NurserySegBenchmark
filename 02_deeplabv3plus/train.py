"""
02_deeplabv3plus/train.py
DeepLabV3+ training portal (based on mmsegmentation Runner)

Usage:
    python train.py --data_root /path/to/work_data_root --work_dir ./work_dirs/deeplabv3plus         [--max_epochs 50] [--batch_size 4] [--lr 1e-4] [--load_from xxx.pth] [--resume]

The default is epoch training (50 epochs), and mIoU early stopping is enabled (patience=15); it can be turned off with --no_early_stop.
work_data_root needs to be generated by ../common/prepare_data.py first (img_dir/ann_dir structure).
"""
import argparse
import os
import sys

# Shared Graphics: Allows the allocator to be closer to "what's actually used" rather than the large reserved cache.
# The available values of this environment variable vary with the PyTorch version and must be set before any CUDA allocation occurs.
# But `import torch` itself will not initialize the CUDA context, so the import here is only used to detect the version number.
import torch as _torch_probe  # noqa: E402

def _set_default_alloc_conf():
    try:
        major, minor = (int(x) for x in _torch_probe.__version__.split("+")[0].split(".")[:2])
    except Exception:
        return  # If the version number parsing fails, no settings will be made, and PyTorch default behavior will be used without risking an error.
    if (major, minor) >= (2, 0):
        # PyTorch 2.x: expandable_segments lets the allocator grow on demand without reserving large chunks of cache
        os.environ.setdefault("PYTORCH_CUDA_ALLOC_CONF", "expandable_segments:True")
    elif (major, minor) >= (1, 10):
        # PyTorch 1.10~1.13: No expandable_segments, use max_split_size_mb to limit single block cache
        # Maximum size, alleviates the problems of large block reservation and fragmentation (weaker than the 2.x solution, but also does not report errors)
        os.environ.setdefault("PYTORCH_CUDA_ALLOC_CONF", "max_split_size_mb:128")
    # PyTorch < 1.10 does not recognize this environment variable (will not read/parse it), and it will be invalid if set, so it is skipped directly.
    # Just use the default allocator behavior of this version, and no errors will be reported due to unknown options being set.


_set_default_alloc_conf()

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

from mmengine.config import Config
from mmengine.runner import Runner

from mmseg.utils import register_all_modules
register_all_modules(init_default_scope=True)

torch = _torch_probe


def parse_args():
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", type=str, default=os.path.join(os.path.dirname(__file__), "config.py"))
    parser.add_argument("--data_root", type=str, required=True)
    parser.add_argument("--work_dir", type=str, default="./work_dirs/deeplabv3plus")
    parser.add_argument("--max_epochs", type=int, default=None)
    parser.add_argument("--batch_size", type=int, default=None)
    parser.add_argument("--lr", type=float, default=None)
    parser.add_argument("--load_from", type=str, default=None)
    parser.add_argument(
        "--gpu_mem_fraction", type=float, default=None,
        help='Limit the maximum proportion of GPU memory available to this process (0~1). It is recommended to set this when sharing the GPU.'
             "For example, 0.4 means using up to 40%% of the current GPU's GPU memory. If it exceeds the limit, it will cause OOM instead of filling up the card.",
    )
    parser.add_argument(
        "--cudnn_benchmark", action="store_true",
        help='Turn on cudnn to automatically select the fastest convolution algorithm. The speed can be improved when using a dedicated GPU, but it will cause problems when using a shared GPU.'
             'The available GPU memory varies each time it is run, resulting in unstable GPU memory usage/speed. It is turned off by default (set to False in config)',
    )
    parser.add_argument("--resume", action="store_true")
    parser.add_argument(
        "--no_early_stop", action="store_true",
        help='Turn off early stopping (config defaults to mIoU early stopping, patience=15).',
    )
    parser.add_argument(
        "--amp", action="store_true",
        help='Turn on automatic mixed precision training (fp16). Turned off by default (i.e. fp32); turning it on can significantly reduce GPU memory usage,'
             'Improved speed, especially for large models such as Swin-Large/MiT-B5. AMP is generally stable for segmentation.'
             'In rare cases, if loss changes to NaN, you can first turn off --amp and use fp32 to troubleshoot.',
    )
    return parser.parse_args()


def main():
    args = parse_args()
    cfg = Config.fromfile(args.config)

    cfg.data_root = args.data_root
    cfg.train_dataloader.dataset.data_root = args.data_root
    cfg.val_dataloader.dataset.data_root = args.data_root
    cfg.work_dir = args.work_dir

    if args.batch_size is not None:
        cfg.train_dataloader.batch_size = args.batch_size
    if args.max_epochs is not None:
        cfg.max_epochs = args.max_epochs
        cfg.train_cfg.max_epochs = args.max_epochs
        # Let the LR scheduling end point follow the total number of rounds (otherwise PolyLR will still decay to 0 in advance according to the end in the config)
        for s in cfg.param_scheduler:
            if s.type == "PolyLR":
                s.end = args.max_epochs
    if args.lr is not None:
        cfg.optim_wrapper.optimizer.lr = args.lr
    if args.load_from is not None:
        cfg.load_from = args.load_from
    if args.resume:
        cfg.resume = True

    if args.no_early_stop:
        cfg.custom_hooks = []
        print("[Early stopping] Disabled via --no_early_stop")

    if args.cudnn_benchmark:
        cfg.env_cfg.cudnn_benchmark = True

    if args.amp:
        cfg.optim_wrapper.type = "AmpOptimWrapper"
        cfg.optim_wrapper.setdefault("loss_scale", "dynamic")
        print("[AMP] Enabled FP16 training with dynamic loss scaling")

    if args.gpu_mem_fraction is not None and torch.cuda.is_available():
        torch.cuda.set_per_process_memory_fraction(args.gpu_mem_fraction, device=0)
        print(f"[Video memory limit] This process can use up to the current GPU memory {args.gpu_mem_fraction:.0%}")

    os.makedirs(cfg.work_dir, exist_ok=True)
    runner = Runner.from_cfg(cfg)
    runner.train()


if __name__ == "__main__":
    main()
